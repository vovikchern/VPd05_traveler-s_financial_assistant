def resolve_country(text: str) -> str | None:
    """Ищет страну по тексту пользователя (без учёта регистра). Возвращает код валюты."""
    normalized = text.strip().lower().replace("ё", "е")
    if normalized in COUNTRIES:
        return COUNTRIES[normalized]
    # частичное совпадение: пользователь написал «южная» вместо «южная корея»
    for name, code in COUNTRIES.items():
        if len(name) > 3 and name in normalized:
            return code
    return None
